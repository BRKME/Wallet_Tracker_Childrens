def targets_for(wallet: str) -> dict:
    return dict(WALLET_TARGETS.get(wallet, BASE_TARGETS))


def hf_act_level() -> float:
    """HF, ниже которого гасим долг: порог минус допуск (1.5 × 0.97 = 1.455)."""
    return HF_FLOOR * (1 - HF_TOLERANCE)


def excluded_alts(wallet: str) -> set:
    return set(WALLET_ALT_EXCLUDE.get(wallet, set()))
